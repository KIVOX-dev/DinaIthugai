export const dictionaries: Record<Locale, Record<DictKey, string>> = { en, ta };

export type Translator = (key: DictKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Locale): Translator {
  const d = dictionaries[lang];
  return (key, vars) => {
    let s = d[key] ?? dictionaries.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Resolve a validation / service error code like "v.required" to a message. */
export function msg(lang: Locale, code: string | undefined): string {
  if (!code) return "";
  const d = dictionaries[lang] as Record<string, string>;
  return d[code] ?? d["v.invalid"];
}

export const STATUS_KEYS = ["draft", "submitted", "in_review", "changes_requested", "approved", "rejected", "scheduled", "published", "unpublished", "archived"] as const;

export function formatDate(iso: string | Date | undefined, lang: Locale, withTime = false) {
  if (!iso) return "";
  const d = typeof iso === "string" ? new Date(iso) : iso;
  return new Intl.DateTimeFormat(lang === "ta" ? "ta-IN" : "en-IN", {
    dateStyle: "medium",
    ...(withTime ? { timeStyle: "short" } : {}),
    timeZone: "Asia/Kolkata",
  }).format(d);
}

export function formatLongDate(d: Date, lang: Locale) {
  return new Intl.DateTimeFormat(lang === "ta" ? "ta-IN" : "en-IN", { dateStyle: "full", timeZone: "Asia/Kolkata" }).format(d);
}
